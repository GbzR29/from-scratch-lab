/** The natural isotopes of element z, lightest first. */
export function isotopesOf(z: number): { a: number; abundance: number; mass: number }[] {
  return Object.entries(STABLE)
    .filter(([k]) => +k.split("-")[0] === z)
    .map(([k, [abundance, mass]]) => ({ a: +k.split("-")[1], abundance, mass }))
    .sort((p, q) => p.a - q.a);
}
